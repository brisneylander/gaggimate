// Synthetic-shot benchmark: the same water draw every time (a 5 s fill at full flow, then 1.8 ml/s for 28 s, through
// the open group, no basket), from a settled 93 °C, alternating the thermal feedforward (Kf) to compare it without
// puck-to-puck variation. Logs each shot from 20 s before to 180 s after to <out dir>/synth-<n>-kf<kf>.csv.
// usage: node synthetic_shot.mjs <out dir> [rounds=3] [kf values=0,0.45,0.7]
import { writeFileSync, appendFileSync } from "node:fs";

const [, , outDir, roundsArg, kfArg] = process.argv;
const host = process.env.GM_HOST || "192.168.20.34";
const base = `http://${host}`;
const ROUNDS = Number(roundsArg || 3);
const KFS = (kfArg || "0,0.45,0.7").split(",").map(Number);
const TARGET = 93;
const SETTLE_BAND = 0.3;
const SETTLE_S = 90;
const AFTER_S = 180;
const PROFILE_ID = "bench-synthetic-shot";
const PROFILE = {
  id: PROFILE_ID,
  label: "[Bench] Synthetic shot",
  type: "pro",
  description:
    "Auto-generated by scripts/bench/synthetic_shot.mjs: a fixed water draw through the open group.",
  temperature: TARGET,
  phases: [
    {
      name: "Fill",
      phase: "preinfusion",
      valve: 1,
      duration: 5,
      temperature: 0,
      transition: { type: "instant", duration: 0, adaptive: true },
      pump: { target: "flow", pressure: 9, flow: 8 },
    },
    {
      name: "Draw",
      phase: "brew",
      valve: 1,
      duration: 28,
      temperature: 0,
      transition: { type: "instant", duration: 0, adaptive: true },
      pump: { target: "flow", pressure: 9, flow: 1.8 },
    },
  ],
};

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const log = (msg) => {
  const line = `${new Date().toISOString().slice(11, 19)} ${msg}`;
  console.log(line);
  appendFileSync(`${outDir}/synth-bench.log`, line + "\n");
};
const post = async (fields) =>
  (
    await fetch(`${base}/api/settings`, {
      method: "POST",
      body: new URLSearchParams(
        Object.entries(fields).map(([k, v]) => [k, String(v)]),
      ),
    })
  ).status;

let ws;
let mode = null;
let ct = null;
let active = false;
let lastTelemetry = Date.now();
let file = null;
let t0 = 0;
let event = "";
const recent = [];
const waiters = new Map();
function connect() {
  ws = new WebSocket(`ws://${host}/ws`);
  ws.onmessage = (e) => {
    const m = JSON.parse(e.data);
    if (waiters.has(m.tp)) {
      waiters.get(m.tp)(m);
      waiters.delete(m.tp);
    }
    if (m.tp === "evt:brew:confirm")
      send({ tp: "req:process:activate", ignoreWarnings: true });
    if (m.tp !== "evt:status") return;
    if (m.m !== undefined) mode = m.m;
    if (m.process !== undefined) active = !!m.process?.a;
    if (m.ct === undefined) return;
    ct = m.ct;
    lastTelemetry = Date.now();
    recent.push({ at: Date.now(), ct });
    while (recent.length && Date.now() - recent[0].at > (SETTLE_S + 10) * 1000)
      recent.shift();
    if (file)
      appendFileSync(
        file,
        `${((Date.now() - t0) / 1000).toFixed(2)},${m.ct},${m.tt},${m.hp},${m.fl},${m.pr},${active ? 1 : 0},${event}\n`,
      );
    event = "";
  };
  ws.onclose = () => setTimeout(connect, 2000);
  ws.onerror = () => {};
}
const send = (obj) => ws.readyState === 1 && ws.send(JSON.stringify(obj));
const request = (obj, reply) =>
  new Promise((resolve) => {
    waiters.set(reply, resolve);
    send(obj);
    setTimeout(() => resolve(null), 10000);
  });

const current = await (await fetch(`${base}/api/settings`)).json();
const saved = { pid: current.pid, standbyTimeout: current.standbyTimeout };
writeFileSync(
  `${outDir}/synth-saved-settings.json`,
  JSON.stringify(saved, null, 2),
);
const [kp, ki, kd] = saved.pid.split(",");

let restored = false;
let selectedBefore = null;
async function restore() {
  if (restored) return;
  restored = true;
  log(`restoring settings: POST ${await post(saved)}`);
  if (selectedBefore)
    await request(
      { tp: "req:profiles:select", id: selectedBefore },
      "res:profiles:select",
    );
  await request(
    { tp: "req:profiles:delete", id: PROFILE_ID },
    "res:profiles:delete",
  );
  log(`profile ${selectedBefore} reselected, bench profile deleted`);
}
async function bail(reason) {
  log(`ABORT: ${reason}`);
  await restore();
  process.exit(1);
}
process.on("SIGINT", () => bail("interrupted"));
// A connection can go quiet without closing (the display drops its oldest client when another connects): reconnect
// after 15 s without telemetry, give up after 2 min.
setInterval(() => {
  const quiet = Date.now() - lastTelemetry;
  if (quiet > 120000) bail("no telemetry for 2 min");
  else if (quiet > 15000 && ws.readyState === 1) {
    log(`no telemetry for ${Math.round(quiet / 1000)} s, reconnecting`);
    ws.close();
  }
}, 2000);

connect();
await sleep(3000);
const list = await request(
  { tp: "req:profiles:list", minimal: false },
  "res:profiles:list",
);
selectedBefore = list?.profiles?.find((p) => p.selected)?.id ?? null;
log(`saved ${JSON.stringify(saved)}, selected profile ${selectedBefore}`);
await post({ standbyTimeout: 0 });
await request(
  { tp: "req:profiles:save", profile: PROFILE },
  "res:profiles:save",
);
await request(
  { tp: "req:profiles:select", id: PROFILE_ID },
  "res:profiles:select",
);
for (let i = 0; i < 15 && mode !== 1; i++) {
  send({ tp: "req:change-mode", mode: 1 });
  await sleep(2000);
}
if (mode !== 1) await bail(`not in Brew (mode ${mode})`);

let n = 0;
for (let round = 1; round <= ROUNDS; round++) {
  for (const kf of KFS) {
    n++;
    const name = `synth-${n}-kf${kf}`;
    log(
      `${name}: PID ${kp},${ki},${kd},${kf}, POST ${await post({ pid: `${kp},${ki},${kd},${kf}` })}`,
    );
    // Settled: every reading of the last SETTLE_S within the band (give up after 15 min if within 0.5 °C).
    const by = Date.now() + 15 * 60000;
    recent.length = 0;
    for (;;) {
      await sleep(2000);
      const span = recent.length
        ? recent[recent.length - 1].at - recent[0].at
        : 0;
      const window = recent.filter((s) => Date.now() - s.at < SETTLE_S * 1000);
      if (
        span > SETTLE_S * 1000 &&
        window.every((s) => Math.abs(s.ct - TARGET) <= SETTLE_BAND)
      )
        break;
      if (Date.now() > by && Math.abs(ct - TARGET) <= 0.5) {
        log(
          `${name}: not within ±${SETTLE_BAND} for ${SETTLE_S} s after 15 min (now ${ct}), starting anyway`,
        );
        break;
      }
    }
    file = `${outDir}/${name}.csv`;
    writeFileSync(file, "t,ct,tt,hp,fl,pr,active,event\n");
    t0 = Date.now();
    await sleep(20000);
    log(`${name}: settled at ${ct}, starting the draw`);
    event = "start";
    send({ tp: "req:process:activate" });
    const startBy = Date.now() + 20000;
    while (!active) {
      if (Date.now() > startBy) await bail("the draw did not start");
      await sleep(250);
    }
    while (active) await sleep(250);
    event = "end";
    log(`${name}: draw ended at ${ct}`);
    await sleep(AFTER_S * 1000);
    log(`${name}: done, ${ct}`);
    file = null;
  }
}
await restore();
log("all draws done");
process.exit(0);
