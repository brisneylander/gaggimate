// Forced cool-down and warm-up run: selects a temporary 30 °C profile (the heater stays off in Brew), flushes to target in
// rests-between bursts until flush to target refuses, then reselects the original profile and logs the warm-up. Not a
// true cold start: the group head stays warmer than the boiler, so keep the results apart from the cold runs.
// Stops if a flush doesn't cool the boiler (an empty tank) or after MAX_ML. Needs a container under the group.
// usage: node force_cool.mjs <out dir>
import { appendFileSync, writeFileSync } from "node:fs";

const [, , outDir = "."] = process.argv;
const HOST = process.env.GM_HOST || "192.168.20.34";
const MAX_ML = 1200;
const REST_S = 60;
const WARM_MIN = 25;
const PROFILE_ID = "bench-cool-30";
const PROFILE = {
  id: PROFILE_ID,
  label: "[Bench] Cool to 30",
  type: "pro",
  description: "Auto-generated by scripts/bench/force_cool.mjs.",
  temperature: 30,
  phases: [
    {
      name: "Hold",
      phase: "brew",
      valve: 1,
      duration: 1,
      temperature: 0,
      transition: { type: "instant", duration: 0, adaptive: true },
      pump: { target: "flow", pressure: 0, flow: 0 },
    },
  ],
};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const log = (m) => {
  const line = `${new Date().toLocaleTimeString("en-GB")} ${m}`;
  console.log(line);
  appendFileSync(`${outDir}/force-cool.log`, line + "\n");
};
let ws;
let s = { ct: null, tt: null, hp: 0, fl: 0, mode: null, active: false };
let file = null;
let t0 = 0;
const waiters = new Map();
function connect() {
  ws = new WebSocket(`ws://${HOST}/ws`);
  ws.onmessage = (e) => {
    const m = JSON.parse(e.data);
    if (waiters.has(m.tp)) {
      waiters.get(m.tp)(m);
      waiters.delete(m.tp);
    }
    if (m.tp !== "evt:status") return;
    if (m.m !== undefined) s.mode = m.m;
    if (m.process !== undefined) s.active = !!m.process?.a;
    if (m.ct === undefined) return;
    Object.assign(s, { ct: m.ct, tt: m.tt, hp: m.hp, fl: m.fl });
    if (file)
      appendFileSync(
        file,
        `${((Date.now() - t0) / 1000).toFixed(1)},${m.ct},${m.tt},${m.hp},${m.fl},${s.mode}\n`,
      );
  };
  ws.onclose = () => setTimeout(connect, 3000);
  ws.onerror = () => {};
}
const send = (o) => ws.readyState === 1 && ws.send(JSON.stringify(o));
const request = (o, reply) =>
  new Promise((resolve) => {
    waiters.set(reply, resolve);
    send(o);
    setTimeout(() => resolve(null), 10000);
  });
async function setMode(m) {
  for (let i = 0; i < 15 && s.mode !== m; i++) {
    send({ tp: "req:change-mode", mode: m });
    await sleep(2000);
  }
  return s.mode === m;
}

connect();
await sleep(3000);
const list = await request({ tp: "req:profiles:list" }, "res:profiles:list");
const original = list?.profiles?.find((p) => p.selected)?.id;
if (!original) throw new Error("no selected profile");
let restored = false;
async function restore() {
  if (restored) return;
  restored = true;
  await request(
    { tp: "req:profiles:select", id: original },
    "res:profiles:select",
  );
  await request(
    { tp: "req:profiles:delete", id: PROFILE_ID },
    "res:profiles:delete",
  );
  log(`profile ${original} reselected, bench profile deleted`);
}
process.on("SIGINT", async () => {
  await restore();
  process.exit(1);
});

log(`start: ${s.ct} °C, mode ${s.mode}, profile ${original}`);
await request(
  { tp: "req:profiles:save", profile: PROFILE },
  "res:profiles:save",
);
await request(
  { tp: "req:profiles:select", id: PROFILE_ID },
  "res:profiles:select",
);
if (!(await setMode(1))) {
  await restore();
  throw new Error("couldn't switch to Brew");
}
await sleep(4000);
log(`Brew, target ${s.tt}`);
if (s.tt !== 30) {
  await restore();
  throw new Error(`target is ${s.tt}, not 30: stopping before any flush`);
}
file = `${outDir}/force-cool.csv`;
writeFileSync(file, "t,ct,tt,hp,fl,mode\n");
t0 = Date.now();
let totalMl = 0;
let why = "";
for (let n = 1; ; n++) {
  if (totalMl >= MAX_ML) {
    why = `reached ${MAX_ML} ml`;
    break;
  }
  const before = s.ct;
  const r = await request(
    { tp: "req:flush:to-target", rid: n },
    "res:flush:to-target",
  );
  if (!r?.success) {
    why = r?.reason || "no reply";
    break;
  }
  totalMl += r.ml;
  log(
    `flush ${n}: ${r.ml} ml in ${r.seconds} s from ${before} °C (total ${totalMl} ml)`,
  );
  await sleep(r.seconds * 1000 + 3000);
  await sleep(REST_S * 1000);
  log(`  after the rest: ${s.ct} °C`);
  if (before - s.ct < 0.5) {
    why = `flush ${n} didn't cool the boiler (${before} -> ${s.ct}): tank empty?`;
    break;
  }
}
log(`cooling stopped: ${why}. ${s.ct} °C after ${totalMl} ml`);
await sleep(30000);
const startC = s.ct;
await restore();
file = `${outDir}/forced-warmup.csv`;
writeFileSync(file, "t,ct,tt,hp,fl,mode\n");
t0 = Date.now();
log(`warm-up from ${startC} °C, target now ${s.tt}`);
const by = Date.now() + WARM_MIN * 60000;
let left = false;
while (Date.now() < by) {
  await sleep(1000);
  if (s.mode !== 1 || s.fl > 0.2 || s.active) {
    left = true;
    log(
      `disturbed: mode ${s.mode}, flow ${s.fl}: leaving the machine as it is`,
    );
    break;
  }
}
file = null;
if (!left)
  log(
    `done at ${s.ct} °C; Standby ${(await setMode(0)) ? "ok" : "not confirmed"}`,
  );
process.exit(0);
